#!/usr/bin/env python3
"""Vendor the ratified Tabler icon subset and flag set into the package.

Tabler Icons and Tabler Flags are MIT licensed. The package does not reference them
from a CDN, because a design contract that changes appearance when a third party
releases is not a contract. Everything is vendored at a pinned upstream tag, recorded
with its SHA-256, and regenerated by this tool rather than hand-copied.

Pinned upstream:

* Tabler Icons  ``v3.49.0``  https://github.com/tabler/tabler-icons
  MIT, (c) 2018-2026 Paweel Kuna. 24x24 grid, 2px stroke, ``currentColor``.
* Tabler Flags  ``v0.1.1``   https://github.com/tabler/tabler-flags
  MIT, (c) 2018-2026 Paweel Kuna. 30x24 canvas, plain paths.

Usage:

    python tools/vendor_icons.py --fetch     # re-download from upstream
    python tools/vendor_icons.py --check     # verify what is vendored, write nothing

``--check`` is the gate. It fails if a vendored file is missing, has drifted from the
recorded digest, or if the license text is absent. It never needs the network.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
import urllib.error
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "assets" / "icons"
ICONS_DIR = ASSETS / "outline"
FLAGS_DIR = ASSETS / "flags"
LICENSE_DIR = ASSETS / "licenses"
MANIFEST = ASSETS / "icon-manifest.json"

ICONS_REPO = "https://raw.githubusercontent.com/tabler/tabler-icons"
ICONS_TAG = "v3.49.0"
FLAGS_REPO = "https://raw.githubusercontent.com/tabler/tabler-flags"
FLAGS_TAG = "v0.1.1"

# The ratified subset. This is the whole point of a curated set: a consumer gets the
# glyphs the contract actually uses, with the upstream set documented but not shipped.
# Names are upstream icon names; the semantic role they fill is recorded in the
# manifest so a consumer can find the right glyph without knowing Tabler.
RATIFIED_ICONS = {
    # navigation and direction
    "arrow-down-right": "directional affordance pointing into a section",
    "arrow-up-right": "external link and reference affordance",
    "arrow-right": "inline progression and row affordance",
    "chevron-down": "disclosure control",
    "chevron-right": "disclosure control, tree and row affordance",
    "arrow-left": "backward navigation",
    # state and status
    "check": "observed success",
    "circle-check": "observed success, primary emphasis",
    "alert-triangle": "warning and operational consequence",
    "circle-x": "refused and prohibited state",
    "loader-2": "pending and in-flight state",
    "clock": "pending state and elapsed time",
    "info-circle": "informational note",
    "circle-dot": "state pip, unlabelled",
    "ban": "prohibited form",
    # content and structure
    "file-text": "document and reference",
    "folder": "grouping and collection",
    "search": "search and filter entry point",
    "settings": "configuration",
    "code": "technical value and source",
    "terminal": "terminal and command surface",
    "layout-grid": "component and grid reference",
    "layers-subtract": "layered surfaces and material families",
    "palette": "colour token reference",
    "typography": "typography reference",
    "contrast": "accessibility and contrast reference",
    "ruler-measure": "measured dimensions",
    "photo": "visual evidence",
    # platform and identity
    "device-desktop": "web target",
    "device-mobile": "mobile target",
    "brand-android": "Android target",
    "cpu": "native target",
    "world": "locale and region",
    "flag": "flag affordance",
    "brand-tabler": "upstream icon set provenance",
    # interaction
    "external-link": "link leaving the product",
    "download": "download affordance",
    "copy": "copy to clipboard",
    "plus": "add affordance",
    "x": "close and dismiss",
    "menu-2": "navigation menu",
}

# The ratified flag subset. Country and organisation flags only; this package does not
# ratify a full flag catalogue, and shipping 300+ flags nobody references would be
# weight without authority.
RATIFIED_FLAGS = {
    "france": "French language and locale reference",
    "united-states": "English (United States) locale reference",
    "united-kingdom": "English (United Kingdom) locale reference",
    "germany": "German language and locale reference",
    "canada": "English and French locale reference",
    "japan": "Japanese language and locale reference",
    "brazil": "Portuguese (Brazil) locale reference",
    "india": "English and Hindi locale reference",
}

ICON_LICENSE_URL = f"{ICONS_REPO}/{ICONS_TAG}/LICENSE"
FLAG_LICENSE_URL = f"{FLAGS_REPO}/{FLAGS_TAG}/LICENSE"


def fetch(url: str) -> bytes:
    request = urllib.request.Request(url, headers={"User-Agent": "gnosix-ds-vendor"})
    with urllib.request.urlopen(request, timeout=30) as response:
        return response.read()


def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def build_sprite(entries: list[dict]) -> bytes:
    """Build an SVG sprite from the vendored icons.

    A sprite is the right form for a consumer surface: one file, one request, and
    ``<use href="sprite.svg#name">`` keeps the glyph recolourable through
    ``currentColor``. Each symbol carries its own viewBox so it renders at the native
    24x24 proportions rather than being scaled into a shared coordinate space.
    """
    symbols = []
    for entry in entries:
        if entry["kind"] != "icon":
            continue
        source = (ROOT / entry["path"]).read_text()
        body = re.search(r"<svg\b[^>]*>(.*)</svg>", source, re.DOTALL)
        if not body:
            raise ValueError(f"{entry['path']} has no <svg> body")
        inner = re.sub(r"<!--.*?-->", "", body.group(1), flags=re.DOTALL).strip()
        symbols.append(f'<symbol id="{entry["name"]}" viewBox="0 0 24 24">{inner}</symbol>')

    return (
        '<svg xmlns="http://www.w3.org/2000/svg" fill="none" stroke="currentColor" '
        'stroke-width="2" stroke-linecap="round" stroke-linejoin="round" '
        'style="display:none">\n'
        + "\n".join(symbols)
        + "\n</svg>\n"
    ).encode("utf-8")


def vendor() -> dict:
    """Download the ratified subset and write it into assets/icons/."""
    ICONS_DIR.mkdir(parents=True, exist_ok=True)
    FLAGS_DIR.mkdir(parents=True, exist_ok=True)
    LICENSE_DIR.mkdir(parents=True, exist_ok=True)

    entries = []
    for name, role in sorted(RATIFIED_ICONS.items()):
        url = f"{ICONS_REPO}/{ICONS_TAG}/icons/outline/{name}.svg"
        data = fetch(url)
        (ICONS_DIR / f"{name}.svg").write_bytes(data)
        entries.append({
            "name": name,
            "kind": "icon",
            "path": f"assets/icons/outline/{name}.svg",
            "role": role,
            "upstream": url,
            "sha256": digest(data),
            "bytes": len(data),
        })

    for name, role in sorted(RATIFIED_FLAGS.items()):
        url = f"{FLAGS_REPO}/{FLAGS_TAG}/src/{name}.svg"
        data = fetch(url)
        (FLAGS_DIR / f"{name}.svg").write_bytes(data)
        entries.append({
            "name": name,
            "kind": "flag",
            "path": f"assets/icons/flags/{name}.svg",
            "role": role,
            "upstream": url,
            "sha256": digest(data),
            "bytes": len(data),
        })

    icon_license = fetch(ICON_LICENSE_URL)
    flag_license = fetch(FLAG_LICENSE_URL)
    (LICENSE_DIR / "Tabler-Icons-LICENSE.txt").write_bytes(icon_license)
    (LICENSE_DIR / "Tabler-Flags-LICENSE.txt").write_bytes(flag_license)

    sprite = build_sprite(entries)
    (ASSETS / "sprite.svg").write_bytes(sprite)

    manifest = {
        "icon_pack": "Tabler Icons",
        "icon_pack_version": ICONS_TAG.lstrip("v"),
        "icon_pack_repo": "https://github.com/tabler/tabler-icons",
        "icon_pack_license": "MIT",
        "flag_pack": "Tabler Flags",
        "flag_pack_version": FLAGS_TAG.lstrip("v"),
        "flag_pack_repo": "https://github.com/tabler/tabler-flags",
        "flag_pack_license": "MIT",
        "attribution": "Copyright (c) 2018-2026 Pawel Kuna",
        "grid": {"icon": "24x24", "flag": "30x24"},
        "stroke": {"icon": "2", "note": "currentColor, 24x24 grid"},
        "sprite": {
            "path": "assets/icons/sprite.svg",
            "sha256": digest(sprite),
            "bytes": len(sprite),
        },
        "entries": entries,
    }
    MANIFEST.write_text(json.dumps(manifest, indent=2) + "\n")
    return manifest


def check() -> int:
    """Verify the vendored subset against the recorded manifest. Never uses the network."""
    if not MANIFEST.is_file():
        print(f"FAIL: {MANIFEST.relative_to(ROOT)} is missing", file=sys.stderr)
        return 1

    manifest = json.loads(MANIFEST.read_text())
    problems = []

    for license_name in ("Tabler-Icons-LICENSE.txt", "Tabler-Flags-LICENSE.txt"):
        path = LICENSE_DIR / license_name
        if not path.is_file():
            problems.append(f"missing {path.relative_to(ROOT)}")
            continue
        text = path.read_text()
        if "MIT License" not in text:
            problems.append(f"{path.relative_to(ROOT)} is not the MIT license text")

    for entry in manifest["entries"]:
        path = ROOT / entry["path"]
        if not path.is_file():
            problems.append(f"missing {entry['path']}")
            continue
        data = path.read_bytes()
        if digest(data) != entry["sha256"]:
            problems.append(f"{entry['path']} does not match its recorded digest")
        if b"<svg" not in data:
            problems.append(f"{entry['path']} is not an SVG")

    for name in sorted(RATIFIED_ICONS):
        if not any(e["name"] == name and e["kind"] == "icon" for e in manifest["entries"]):
            problems.append(f"icon {name} is ratified but not vendored")
    for name in sorted(RATIFIED_FLAGS):
        if not any(e["name"] == name and e["kind"] == "flag" for e in manifest["entries"]):
            problems.append(f"flag {name} is ratified but not vendored")

    sprite_info = manifest.get("sprite")
    if not sprite_info:
        problems.append("manifest records no sprite")
    else:
        sprite_path = ROOT / sprite_info["path"]
        if not sprite_path.is_file():
            problems.append(f"missing {sprite_info['path']}")
        elif digest(sprite_path.read_bytes()) != sprite_info["sha256"]:
            problems.append(f"{sprite_info['path']} does not match its recorded digest")
        else:
            sprite_text = sprite_path.read_text()
            for entry in manifest["entries"]:
                if entry["kind"] != "icon":
                    continue
                if f'id="{entry["name"]}"' not in sprite_text:
                    problems.append(f"sprite has no symbol for {entry['name']}")

    for problem in problems:
        print(f"FAIL: {problem}", file=sys.stderr)
    if problems:
        return 1

    icons = sum(1 for e in manifest["entries"] if e["kind"] == "icon")
    flags = sum(1 for e in manifest["entries"] if e["kind"] == "flag")
    print(
        f"icon pack: {manifest['icon_pack']} {manifest['icon_pack_version']} "
        f"({icons} icons vendored), {manifest['flag_pack']} "
        f"{manifest['flag_pack_version']} ({flags} flags vendored), licenses present"
    )
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--fetch", action="store_true", help="download from upstream and vendor")
    group.add_argument("--check", action="store_true", help="verify the vendored subset")
    args = parser.parse_args()

    if args.fetch:
        manifest = vendor()
        print(f"vendored {len(manifest['entries'])} assets into assets/icons/")
        return 0
    return check()


if __name__ == "__main__":
    sys.exit(main())
